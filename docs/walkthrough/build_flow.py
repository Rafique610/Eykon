#!/usr/bin/env python3
"""Build the interactive pipeline map (ANALYSIS.md, Phase 4).

    uv run --no-project python docs/walkthrough/build_flow.py      (or: task build-flow)

Reads flow/index.json, every stage file it lists and the stage docs, and writes next to this script:
  flow.html            one self-contained page: data, styles and code inline, no network (from flow_template.html)
  flow-overview.mmd    the overview as a Mermaid flowchart
  flow-overview.svg    the overview drawn by Graphviz, only when `dot` is installed
Run validate_flow.py first: this script trusts the data. Standard library only.
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from validate_flow import anchors, slug  # noqa: E402  (one anchor rule for both scripts)


def sections(text: str) -> dict[str, str]:
    """Anchor -> that section's markdown, from its heading to the next heading of the same or a higher level."""
    lines = re.sub(r"<!--.*?-->", "", text, flags=re.S).splitlines()
    marks, fenced = [], False
    for i, line in enumerate(lines):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
        elif not fenced and (m := re.match(r"(#{1,6})\s+(.+?)\s*#*\s*$", line)):
            marks.append((i, len(m.group(1)), m.group(2)))
    names, seen = [], {}
    for _, _, title in marks:
        base = slug(title)
        names.append(f"{base}-{seen[base]}" if base in seen else base)
        seen[base] = seen.get(base, 0) + 1
    assert names == anchors(text), "anchor rule differs from validate_flow.py"
    out = {}
    for k, (i, level, _) in enumerate(marks):
        end = next((j for j, lv, _ in marks[k + 1:] if lv <= level), len(lines))
        out[names[k]] = "\n".join(lines[i:end]).strip()
    return out


def mermaid_id(stage_id: str) -> str:
    return stage_id.replace("-", "_")


def mermaid_text(text: str) -> str:
    return text.replace('"', "#quot;").replace("<", "#lt;").replace(">", "#gt;")


def mermaid(index: dict) -> str:
    """The overview as a Mermaid flowchart: one box per stage, grouped by platform and flow; offline edges dashed."""
    lines = ["%% Generated by docs/walkthrough/build_flow.py from flow/index.json. Do not edit by hand.", "flowchart LR"]
    groups: dict[tuple[str, str], list[dict]] = {}
    for stage in index["stages"]:
        groups.setdefault((stage["flow"], stage.get("platform", "")), []).append(stage)
    for (flow, platform), stages in groups.items():
        lines.append(f'  subgraph {flow}_{platform}["{platform}, {flow}"]')
        lines += [f'    {mermaid_id(s["id"])}["{mermaid_text(s["id"][:3] + " " + s["label"])}"]' for s in stages]
        lines.append("  end")
    for e in index["edges"]:
        arrow = "-->" if e["flow"] == "runtime" else "-.->"
        lines.append(f'  {mermaid_id(e["from"])} {arrow}|"{mermaid_text(e["label"])}"| {mermaid_id(e["to"])}')
    return "\n".join(lines) + "\n"


def graphviz(index: dict) -> str:
    """Draws flow-overview.svg with Graphviz when it is installed; returns what happened."""
    dot = shutil.which("dot")
    if not dot:
        return "flow-overview.svg skipped: Graphviz (dot) is not installed (sudo apt install graphviz)"
    def q(text: str) -> str:
        return json.dumps(text, ensure_ascii=False)
    body = [f'  {q(s["id"])} [label={q(s["id"][:3] + chr(10) + s["label"])}, style="rounded{",dashed" if s["flow"] == "offline" else ""}"];'
            for s in index["stages"]]
    body += [f'  {q(e["from"])} -> {q(e["to"])} [label={q(e["label"])}{", style=dashed" if e["flow"] == "offline" else ""}];'
             for e in index["edges"]]
    source = "digraph overview {\n  rankdir=LR; node [shape=box, fontname=Helvetica, fontsize=11]; edge [fontsize=9];\n"
    source += "\n".join(body) + "\n}\n"
    subprocess.run([dot, "-Tsvg", "-o", str(HERE / "flow-overview.svg")], input=source, text=True, check=True)
    return "wrote flow-overview.svg"


def main() -> int:
    index = json.loads((HERE / "flow" / "index.json").read_text(encoding="utf-8"))
    nodes: dict[str, dict] = {}
    edges: list[dict] = []
    for rel in index["stage_files"]:
        stage = json.loads((HERE / rel).read_text(encoding="utf-8"))
        for node in [stage["stage"], *stage["nodes"]]:
            nodes[node["id"]] = node
        edges += stage["edges"]
    docs: dict[str, str] = {}
    for md in sorted((HERE / "stages").glob("s[0-9][0-9]-*.md")):
        parts = sections(md.read_text(encoding="utf-8"))
        for node in nodes.values():
            doc, _, anchor = node["doc"].partition("#")
            if doc == f"stages/{md.name}" and anchor in parts:
                docs[node["doc"]] = parts[anchor]
    data = {"project": index["project"], "stages": index["stages"], "stageEdges": index["edges"],
            "traces": index["traces"], "nodes": nodes, "edges": edges, "docs": docs}
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    template = (HERE / "flow_template.html").read_text(encoding="utf-8")
    if template.count("__FLOW_DATA__") != 1:
        sys.exit("flow_template.html must hold the __FLOW_DATA__ placeholder exactly once")
    (HERE / "flow.html").write_text(template.replace("__FLOW_DATA__", payload), encoding="utf-8")
    (HERE / "flow-overview.mmd").write_text(mermaid(index), encoding="utf-8")
    print(f"wrote flow.html ({len(nodes)} nodes, {len(edges)} edges, {len(docs)} doc sections) and flow-overview.mmd")
    print(graphviz(index))
    return 0


if __name__ == "__main__":
    sys.exit(main())
