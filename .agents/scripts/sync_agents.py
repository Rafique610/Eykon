"""Generate per-tool agent files from the canonical .agents/agents/ source.

Usage:
    uv run python .agents/scripts/sync_agents.py          # write generated files
    uv run python .agents/scripts/sync_agents.py --check  # fail if stale, no writes
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AGENTS_DIR = ROOT / ".agents" / "agents"
GENERATED_MARKER = "<!-- GENERATED by .agents/scripts/sync_agents.py — edit the source in .agents/agents/, do not edit this file directly. -->"

NAME_RE = re.compile(r"^[a-z0-9-]+$")


def load_agents() -> list[dict]:
    agents = []
    for entry in sorted(AGENTS_DIR.iterdir()):
        if not entry.is_dir():
            continue
        meta_path = entry / "agent.json"
        prompt_path = entry / "prompt.md"
        if not meta_path.exists() or not prompt_path.exists():
            continue
        if not NAME_RE.match(entry.name):
            raise ValueError(f"invalid agent name {entry.name!r}: must match [a-z0-9-]+")
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        if "description" not in meta:
            raise ValueError(f"{entry.name}: agent.json is missing required 'description'")
        meta["name"] = entry.name
        meta["prompt"] = prompt_path.read_text(encoding="utf-8").strip()
        agents.append(meta)
    return agents


def target_override(agent: dict, tool: str) -> dict | str | None:
    return agent.get("targets", {}).get(tool)


# Claude Code tool names are capitalized; multi-word ones aren't plain
# Title Case (WebFetch, not Webfetch), so exceptions are spelled out here.
CLAUDE_TOOL_NAMES = {
    "webfetch": "WebFetch",
    "websearch": "WebSearch",
    "notebookedit": "NotebookEdit",
}


def claude_tool_name(tool: str) -> str:
    return CLAUDE_TOOL_NAMES.get(tool, tool.capitalize())


def render_claude(agent: dict) -> str:
    override = target_override(agent, "claude") or {}
    lines = [GENERATED_MARKER, "---", f"name: {agent['name']}", f"description: {agent['description']}"]
    if agent.get("model"):
        lines.append(f"model: {agent['model']}")
    if agent.get("tools"):
        lines.append(f"tools: {', '.join(claude_tool_name(t) for t in agent['tools'])}")
    for key, value in override.items():
        lines.append(f"{key}: {value}")
    lines += ["---", "", agent["prompt"], ""]
    return "\n".join(lines)


def render_opencode(agent: dict) -> str:
    override = target_override(agent, "opencode") or {}
    lines = [GENERATED_MARKER, "---", f"description: {agent['description']}"]
    if agent.get("model"):
        lines.append(f"model: {agent['model']}")
    if agent.get("tools"):
        lines.append("tools:")
        for tool in agent["tools"]:
            lines.append(f"  {tool}: true")
    for key, value in override.items():
        lines.append(f"{key}: {value}")
    lines += ["---", "", agent["prompt"], ""]
    return "\n".join(lines)


def render_openai_catalog(agents: list[dict]) -> str:
    lines = [
        GENERATED_MARKER,
        "# OpenAI / Codex agent catalog",
        "",
        "There is no standardized per-file subagent format for OpenAI-based "
        "tools yet, so this is a single reference catalog instead of one "
        "file per agent. Paste the relevant section into an Agent Builder "
        "config, a Codex prompt, or an Assistants API `instructions` field.",
        "",
    ]
    if not agents:
        lines.append("_No agents defined yet — add one under `.agents/agents/`._")
    for agent in agents:
        if target_override(agent, "openai") == "skip":
            continue
        lines += [f"## {agent['name']}", "", f"**When to use:** {agent['description']}", "", agent["prompt"], ""]
    return "\n".join(lines)


TARGETS = {
    "claude": {
        "dir": ROOT / ".claude" / "agents",
        "render": lambda agents: {
            ROOT / ".claude" / "agents" / f"{a['name']}.md": render_claude(a)
            for a in agents
            if target_override(a, "claude") != "skip"
        },
    },
    "opencode": {
        "dir": ROOT / ".opencode" / "agent",
        "render": lambda agents: {
            ROOT / ".opencode" / "agent" / f"{a['name']}.md": render_opencode(a)
            for a in agents
            if target_override(a, "opencode") != "skip"
        },
    },
    "openai": {
        "dir": ROOT / ".agents" / "export",
        "render": lambda agents: {ROOT / ".agents" / "export" / "openai-agents.md": render_openai_catalog(agents)},
    },
}


def managed_files(directory: Path) -> list[Path]:
    if not directory.exists():
        return []
    return [p for p in directory.glob("*.md") if GENERATED_MARKER in p.read_text(encoding="utf-8")]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale, write nothing")
    args = parser.parse_args()

    agents = load_agents()

    desired: dict[Path, str] = {}
    for target in TARGETS.values():
        desired.update(target["render"](agents))

    stale = []
    for path, content in desired.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)

    stray = []
    for target in TARGETS.values():
        for existing in managed_files(target["dir"]):
            if existing not in desired:
                stray.append(existing)

    if args.check:
        if stale or stray:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)}")
            for path in stray:
                print(f"orphaned: {path.relative_to(ROOT)}")
            return 1
        print(f"{len(agents)} agent(s), {len(desired)} generated file(s) — all in sync.")
        return 0

    for path in stray:
        path.unlink()
    for path, content in desired.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    print(f"Synced {len(agents)} agent(s) -> {len(desired)} generated file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
